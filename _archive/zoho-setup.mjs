#!/usr/bin/env node
/**
 * Zoho Mail API setup helper (local only — never deployed).
 * ---------------------------------------------------------------------------
 * Run from this folder. It talks to Zoho over HTTPS and writes the three
 * secrets into `.dev.vars` so `wrangler dev` can send real mail.
 *
 * The fastest route is a Zoho "Self Client", which needs no redirect URI:
 *
 *   1. https://api-console.zoho.in  →  Add Client  →  Self Client
 *   2. Copy the Client ID and Client Secret.
 *   3. In the Self Client "Generate Code" tab, add this scope:
 *        ZohoMail.messages.CREATE,ZohoMail.accounts.READ
 *      choose a duration (e.g. 10 minutes) and copy the generated code.
 *   4. node zoho-setup.mjs exchange <CLIENT_ID> <CLIENT_SECRET> <CODE>
 *   5. node zoho-setup.mjs verify
 *
 * Commands
 *   url <clientId> [redirectUri]                  print a consent URL (Server-based clients only)
 *   exchange <clientId> <secret> <code> [redirect]   swap the code for a refresh token
 *   verify                                        check the token + mailbox in .dev.vars
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DC = process.env.ZOHO_DC || "in";
const SCOPES = "ZohoMail.messages.CREATE,ZohoMail.accounts.READ";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const DEV_VARS = path.join(HERE, ".dev.vars");

const ACCOUNTS = `https://accounts.zoho.${DC}`;
const MAIL = `https://mail.zoho.${DC}`;

const [cmd, ...args] = process.argv.slice(2);

function readDevVars() {
  const out = {};
  if (!fs.existsSync(DEV_VARS)) return out;
  for (const raw of fs.readFileSync(DEV_VARS, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    out[line.slice(0, eq).trim()] = line.slice(eq + 1).trim();
  }
  return out;
}

function writeDevVars(values) {
  const lines = [
    "# Generated by zoho-setup.mjs — local only, never deployed (.assetsignore excludes it).",
    `ZOHO_CLIENT_ID=${values.ZOHO_CLIENT_ID || ""}`,
    `ZOHO_CLIENT_SECRET=${values.ZOHO_CLIENT_SECRET || ""}`,
    `ZOHO_REFRESH_TOKEN=${values.ZOHO_REFRESH_TOKEN || ""}`,
  ];
  if (values.ZOHO_ACCOUNT_ID) lines.push(`ZOHO_ACCOUNT_ID=${values.ZOHO_ACCOUNT_ID}`);
  if (DC !== "in") lines.push(`ZOHO_DC=${DC}`);
  fs.writeFileSync(DEV_VARS, lines.join("\n") + "\n", "utf8");
}

async function exchange(clientId, clientSecret, code, redirectUri) {
  const body = new URLSearchParams({
    grant_type: "authorization_code",
    client_id: clientId,
    client_secret: clientSecret,
    code,
  });
  if (redirectUri) body.set("redirect_uri", redirectUri);

  const res = await fetch(`${ACCOUNTS}/oauth/v2/token`, {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body,
  });
  const data = await res.json().catch(() => ({}));

  if (!data.refresh_token) {
    console.error("\nZoho rejected the exchange:\n" + JSON.stringify(data, null, 2));
    console.error(
      "\nCommon causes: the code expired (Self Client codes are short-lived — generate a fresh one), " +
        "the scope is missing, or the code was already used.",
    );
    process.exit(1);
  }

  writeDevVars({
    ZOHO_CLIENT_ID: clientId,
    ZOHO_CLIENT_SECRET: clientSecret,
    ZOHO_REFRESH_TOKEN: data.refresh_token,
  });

  console.log("\n✅ Wrote .dev.vars with a fresh refresh token.");
  console.log("   Next:  npx.cmd wrangler dev --config wrangler.jsonc");
  console.log("   Then:  node zoho-setup.mjs verify");
}

async function verify() {
  const v = readDevVars();
  if (!v.ZOHO_CLIENT_ID || !v.ZOHO_CLIENT_SECRET || !v.ZOHO_REFRESH_TOKEN) {
    console.error("❌ .dev.vars is missing ZOHO_CLIENT_ID / ZOHO_CLIENT_SECRET / ZOHO_REFRESH_TOKEN.");
    process.exit(1);
  }

  const body = new URLSearchParams({
    grant_type: "refresh_token",
    client_id: v.ZOHO_CLIENT_ID,
    client_secret: v.ZOHO_CLIENT_SECRET,
    refresh_token: v.ZOHO_REFRESH_TOKEN,
  });
  const tr = await fetch(`${ACCOUNTS}/oauth/v2/token`, {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body,
  });
  const td = await tr.json().catch(() => ({}));
  if (!td.access_token) {
    console.error("❌ Token refresh failed:\n" + JSON.stringify(td, null, 2));
    process.exit(1);
  }
  console.log("✅ Access token obtained.");

  const ar = await fetch(`${MAIL}/api/accounts`, {
    headers: { Authorization: `Zoho-oauthtoken ${td.access_token}`, Accept: "application/json" },
  });
  const ad = await ar.json().catch(() => ({}));
  const account = ad?.data?.[0];
  if (!account?.accountId) {
    console.error("❌ Account lookup failed:\n" + JSON.stringify(ad, null, 2));
    process.exit(1);
  }
  console.log(`✅ Mailbox: ${account.primaryEmailAddress || account.mailboxAddress || "(unknown)"}`);
  console.log(`   accountId: ${account.accountId}`);
  console.log("\nEverything works. Start the dev server and submit the form.");
}

function printUrl(clientId, redirectUri) {
  const u = new URL(`${ACCOUNTS}/oauth/v2/auth`);
  u.searchParams.set("scope", SCOPES);
  u.searchParams.set("client_id", clientId);
  u.searchParams.set("response_type", "code");
  u.searchParams.set("access_type", "offline");
  u.searchParams.set("prompt", "consent");
  if (redirectUri) u.searchParams.set("redirect_uri", redirectUri);
  console.log("\nOpen this URL, sign in as the audit@ mailbox owner, and approve:\n");
  console.log(u.toString());
  console.log("\nThen copy the `code` query parameter from the redirect and run:");
  console.log(`  node zoho-setup.mjs exchange ${clientId} <SECRET> <CODE> ${redirectUri || "<REDIRECT_URI>"}`);
}

switch (cmd) {
  case "exchange": {
    const [clientId, clientSecret, code, redirectUri] = args;
    if (!clientId || !clientSecret || !code) {
      console.error("Usage: node zoho-setup.mjs exchange <CLIENT_ID> <CLIENT_SECRET> <CODE> [REDIRECT_URI]");
      process.exit(1);
    }
    await exchange(clientId, clientSecret, code, redirectUri);
    break;
  }
  case "verify":
    await verify();
    break;
  case "url": {
    const [clientId, redirectUri] = args;
    if (!clientId) {
      console.error("Usage: node zoho-setup.mjs url <CLIENT_ID> [REDIRECT_URI]");
      process.exit(1);
    }
    printUrl(clientId, redirectUri);
    break;
  }
  default:
    console.log(`Zoho Mail API setup helper (data centre: ${DC})

  1. Create a Self Client:  https://api-console.zoho.in  ->  Add Client  ->  Self Client
     - copy Client ID + Client Secret
     - "Generate Code" tab, scope: ${SCOPES}
     - copy the generated code

  2. node zoho-setup.mjs exchange <CLIENT_ID> <CLIENT_SECRET> <CODE>
  3. node zoho-setup.mjs verify
  4. npx.cmd wrangler dev --config wrangler.jsonc

  (Server-based client instead of Self Client? Get a consent URL with:
     node zoho-setup.mjs url <CLIENT_ID> <REDIRECT_URI> )`);
}
